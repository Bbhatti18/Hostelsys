-- Require confirmed canonical terms under the existing financial/admission locks.
-- Remove the old entry point so no service-role caller can bypass confirmation.
begin;
drop function public.generate_missing_staff_rent(uuid,text,text);
create function public.generate_missing_staff_rent(p_admission uuid,p_month text,p_actor text,p_expected_amount numeric,p_expected_due_date date) returns uuid
language plpgsql security definer set search_path=pg_catalog,public as $$
declare a public.admissions%rowtype; amount numeric; canonical_due date; key uuid:=gen_random_uuid();
begin
 perform public.require_allocation_actor(p_actor,true);
 perform public.lock_financial_ledger();
 select * into a from public.admissions where id=p_admission for update;
 if a.id is null or a.status not in ('Pending','Active') or p_month is null or p_month !~ '^\d{4}-(0[1-9]|1[0-2])$'
 or p_month<to_char(a.admission_date,'YYYY-MM') or p_month>to_char((now() at time zone 'Asia/Karachi')::date,'YYYY-MM')
 or exists(select 1 from public.residents where id=a.resident_id and status='Archived')
 or exists(select 1 from public.admissions n where n.resident_id=a.resident_id and (n.admission_date,n.created_at,n.id)>(a.admission_date,a.created_at,a.id)) then raise exception 'Current admission and missing elapsed/current month required.'; end if;
 perform 1 from public.bills where admission_id=a.id and bill_type='Rent' and billing_month=p_month for update;
 if exists(select 1 from public.bills where admission_id=a.id and bill_type='Rent' and billing_month=p_month) then raise exception 'Rent bill already exists, including cancelled or paid history.'; end if;
 amount:=a.monthly_rent;
 if amount is null or amount<=0 then select monthly_rent into amount from public.contracts where admission_id=a.id and status not in ('Cancelled','Terminated') order by created_at desc,id desc limit 1 for update; end if;
 if amount is null or amount<=0 then raise exception 'Canonical monthly rent is missing.'; end if;
 canonical_due:=public.admission_rent_due_date(a.admission_date,p_month);
 if p_expected_amount is null or p_expected_due_date is null
 or amount is distinct from p_expected_amount or canonical_due is distinct from p_expected_due_date then
   raise exception 'Rent amount or due date changed. Reload the preview.' using errcode='23514';
 end if;
 insert into public.bills(id,bill_number,resident_id,admission_id,bill_type,billing_month,due_date,rent_amount,total_amount,bill_status,notes)
 values(key,'RENT-MISSING-'||key::text,a.resident_id,a.id,'Rent',p_month,canonical_due,amount,amount,'Pending Approval','Missing rent generated by '||p_actor||'; rent only; utilities use their existing workflow.');
 return key;
end; $$;
revoke all on function public.generate_missing_staff_rent(uuid,text,text,numeric,date) from public,anon,authenticated,service_role;
grant execute on function public.generate_missing_staff_rent(uuid,text,text,numeric,date) to service_role;
commit;
